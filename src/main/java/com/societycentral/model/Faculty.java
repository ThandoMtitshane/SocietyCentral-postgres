package com.societycentral.model;

/**
 * The 7 faculties of Nelson Mandela University, plus NONE for
 * societies/students that are not scoped to any specific faculty
 * (e.g. religious or special-interest societies).
 */
public enum Faculty {
    BUSINESS_AND_ECONOMIC_SCIENCES,
    EDUCATION,
    ENGINEERING_BUILT_ENVIRONMENT_AND_TECHNOLOGY,
    HEALTH_SCIENCES,
    HUMANITIES,
    LAW,
    SCIENCE,
    NONE
}
